// One nested object per language, not a flat "a.b.c" string-key lookup --
// components just destructure the slice they need off `t` (e.g.
// `t.settings.language`), which is plain JS and needs no path-parsing
// helper. Leaves that need a variable (relative time, "Xth matchday", an
// aria-label naming a specific club) are functions instead of strings,
// called as `t.transfers.daysAgo(3)`.
//
// Never translated here (kept as-is by the calling component instead):
// club/player names, league names (Serie A, Bundesliga, Premier League,
// Ligue 1, LaLiga -- official spellings per lib/leagues.js), source names
// (kicker, tuttomercatoweb, marca, ...), and the "KickRadar" brand name.

// English ordinal suffix (1st, 2nd, 3rd, 4th, 11th, 21st, ...) -- used by
// en.stats.positionLabel. The other languages' ordinal marks are fixed
// (German ".", Italian "°", Spanish "º") or a simple 1-vs-rest split
// (French "er"/"e"), so only English needs real logic.
function ordinalEn(n) {
  const v = n % 100;
  if (v >= 11 && v <= 13) return `${n}th`;
  switch (n % 10) {
    case 1:
      return `${n}st`;
    case 2:
      return `${n}nd`;
    case 3:
      return `${n}rd`;
    default:
      return `${n}th`;
  }
}

